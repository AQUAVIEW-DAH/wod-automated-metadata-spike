"""Write biological hauls (plankton counts, biomass) as WOD Taxa-Records in a ragged NetCDF.

One `casts` entry per haul (position, time, Biological Header as `b_<id>_<name>`, Table 6a)
and one `taxa_obs` entry per Taxa-Record (`t_<id>_<name>`, Table 7a), contiguous by haul.
Headers, notes, time and cast ids use the profile writer's helpers.
"""
import os
import re
from typing import Any, Dict, List

import netCDF4 as nc
import numpy as np

from wod_etl.config import CF_CONVENTIONS, NETCDF_FILL_VALUE, TOOL_NAME, WOD_VERSION
from wod_etl.reference import biological_headers, taxa_biomass_variables
from wod_etl.writers.generate_netcdf_ragged import (
    CAST_DIM, _cast_ids, _cast_times, _cast_var, _coord, _describe_time,
    _write_character_data, _write_provenance, _write_shared_secondary_headers,
    _write_time_zones, _write_varying_secondary_headers, cf_safe_name, split_coded_value)

OBS_DIM = "taxa_obs"
INT_FILL = np.int32(-2147483647)

# Table 7a fields written as numbers (float), by id. Coded fields (5, 6, 7...) are written
# separately as codes plus the originator's text.
_NUMERIC_FIELDS = (2, 3, 4, 10, 11, 12, 13, 14, 15, 18, 19, 21, 22, 23, 25)
_CODED_FIELDS = (5, 6, 7, 8, 9, 16, 17, 26)


def write_taxa_netcdf(hauls: List[Dict[str, Any]], output_path: str) -> Dict[str, Any]:
    """Write hauls (from `wod_etl.mapping.map_haul`) to one file. Never raises on data."""
    if not hauls:
        return {"status": "error", "error": "no hauls supplied", "output_path": output_path}
    parent = os.path.dirname(os.path.abspath(output_path))
    os.makedirs(parent, exist_ok=True)

    casts = [{"contract": h["contract"]} for h in hauls]
    sizes = [len(h["records"]) for h in hauls]
    total = int(sum(sizes))
    records = [r for h in hauls for r in h["records"]]
    t7a = taxa_biomass_variables()
    t6a = biological_headers()

    with nc.Dataset(output_path, "w", format="NETCDF4") as ds:
        ds.createDimension(CAST_DIM, len(hauls))
        ds.createDimension(OBS_DIM, total)

        ds.title = "WOD Intermediate Taxa-Records"
        ds.Conventions = CF_CONVENTIONS
        ds.WOD_version = WOD_VERSION
        ds.wod_dataset_type = "OSD"
        ds.wod_record_model = ("Biological Header (Table 6a) per haul; Taxa-Records (Table 7a) "
                               "per taxon x depth range x measurement")
        ds.source_file = "; ".join(dict.fromkeys(str(c["contract"].get("source") or "")
                                                 for c in casts))
        raw = list(dict.fromkeys(p for c in casts for p in c["contract"].get("source_files") or []))
        if raw:
            ds.source_files_raw = "; ".join(raw)
        ds.source = f"generated by {TOOL_NAME}"
        _write_provenance(ds, casts)
        _write_character_data(ds, casts)
        _write_shared_secondary_headers(ds, casts)

        _cast_var(ds, "lat", "f8", [_coord(c, "latitude") for c in casts],
                  units="degrees_north", standard_name="latitude", long_name="haul latitude")
        _cast_var(ds, "lon", "f8", [_coord(c, "longitude") for c in casts],
                  units="degrees_east", standard_name="longitude", long_name="haul longitude")
        times = _cast_times(casts)
        tv = ds.createVariable("time", "f8", (CAST_DIM,), fill_value=np.nan)
        tv.units = "days since 1770-01-01 00:00:00"
        tv.standard_name = "time"
        tv.calendar = "gregorian"
        tv[:] = times["time"]
        _describe_time(tv, times)
        dv = ds.createVariable("date", "i4", (CAST_DIM,), fill_value=INT_FILL)
        dv.long_name = "haul date, YYYYMMDD"
        dv[:] = np.array(times["date"], dtype="i4")
        gv = ds.createVariable("GMT_time", "f4", (CAST_DIM,), fill_value=NETCDF_FILL_VALUE)
        gv.units = "hours"
        gv.long_name = "haul time of day, decimal hours UTC; fill when not stated"
        gv[:] = np.array(times["hours"], dtype="f4")
        _write_time_zones(ds, casts, times)
        idv = ds.createVariable("cast_id", str, (CAST_DIM,))
        idv.long_name = "haul identifier"
        for i, cid in enumerate(_cast_ids(casts)):
            idv[i] = cid
        rs = ds.createVariable("taxa_row_size", "i4", (CAST_DIM,))
        rs.long_name = "number of Taxa-Records in this haul"
        rs.sample_dimension = OBS_DIM
        rs[:] = np.array(sizes, dtype="i4")
        _write_varying_secondary_headers(ds, casts)

        _write_biological_header(ds, hauls, t6a)
        written = _write_records(ds, records, total, t7a)

    return {"status": "success", "output_path": output_path, "hauls": len(hauls),
            "taxa_records": total, "fields_written": written}


def _write_biological_header(ds, hauls, t6a) -> None:
    ids = sorted({fid for h in hauls for fid in h.get("biological_header", {})})
    for fid in ids:
        meta = t6a.get(fid, {"name": f"field {fid}"})
        key = f"b_{fid}_{cf_safe_name(meta['name'])}"
        entries = [h.get("biological_header", {}).get(fid) or {} for h in hauls]
        split = [split_coded_value(e) if e else (None, None, None) for e in entries]
        values, texts, lookups = ([x[0] for x in split], [x[1] for x in split],
                                  [x[2] for x in split])
        numeric = meta.get("unit") is not None and not meta.get("appendix")
        if numeric:
            nums = [_float(x) for x in values]
            # Keep non-numeric text ('100 um') beside the field rather than a bare fill.
            texts = [t if t is not None else
                     (str(x) if x not in (None, "") and not np.isfinite(n) else None)
                     for t, x, n in zip(texts, values, nums)]
            v = ds.createVariable(key, "f4", (CAST_DIM,), fill_value=NETCDF_FILL_VALUE)
            v[:] = np.array(nums, dtype="f4")
            v.units = str(meta["unit"])
        elif any(x is not None for x in values):
            v = ds.createVariable(key, str, (CAST_DIM,))
            for i, x in enumerate(values):
                v[i] = "" if x is None else str(x)
        else:
            v = None
        if v is not None:
            v.long_name = meta["name"]
            v.wod_biological_header_id = np.int32(fid)
        for suffix, series in (("_originator_text", texts), ("_code_lookup", lookups)):
            if any(x is not None for x in series):
                t = ds.createVariable(f"{key}{suffix}", str, (CAST_DIM,))
                t.long_name = f"{meta['name']}: " + ("originator's text, not a code"
                                                    if suffix == "_originator_text"
                                                    else "code lookup result")
                for i, x in enumerate(series):
                    t[i] = "" if x is None else str(x)


def _write_records(ds, records, total, t7a) -> List[str]:
    written = []

    def obs(name, dtype, values, fill, **attrs):
        v = ds.createVariable(name, dtype, (OBS_DIM,),
                              **({"fill_value": fill} if fill is not None else {}))
        if dtype == str:
            for i, x in enumerate(values):
                v[i] = "" if x is None else str(x)
        else:
            v[:] = np.array(values, dtype=dtype)
        for k, val in attrs.items():
            v.setncattr(k, val)
        written.append(name)
        return v

    obs("t_1_variable_number", "i4",
        [r["taxon"]["code"] if r["taxon"]["code"] is not None else INT_FILL for r in records],
        INT_FILL, long_name="Taxa-Record variable number: ITIS TSN (> 0) or WOD code (< 0)",
        wod_taxa_variable_id=np.int32(1),
        code_table="https://www.ncei.noaa.gov/access/world-ocean-database/CODES/t_1_taxa_list.html")
    obs("taxon_name_originator", str, [r["taxon"]["originator_name"] for r in records], None,
        long_name="taxon as the originator wrote it")
    obs("taxon_resolution", str,
        [r["taxon"]["status"] + (f": {r['taxon']['note']}" if r["taxon"].get("note") else "")
         for r in records], None, long_name="how the variable number was resolved")
    obs("t_30_plankton_grouping_code", "i4",
        [r["taxon"]["pgc"] if r["taxon"].get("pgc") is not None else INT_FILL for r in records],
        INT_FILL, long_name="Plankton Grouping Code (Table 9)",
        wod_taxa_variable_id=np.int32(30))

    present = sorted({fid for r in records for fid in r["fields"]})
    for fid in present:
        meta = t7a.get(fid, {"name": f"field {fid}"})
        name = f"t_{fid}_{cf_safe_name(meta['name'])}"
        if fid in _NUMERIC_FIELDS:
            v = obs(name, "f4", [_float(r["fields"].get(fid)) for r in records],
                    NETCDF_FILL_VALUE, long_name=meta["name"],
                    wod_taxa_variable_id=np.int32(fid))
            if meta.get("unit"):
                v.units_rule = str(meta["unit"])
            if fid in (2, 3):
                v.units = "meters"
        elif fid in _CODED_FIELDS:
            coded = [r["coded"].get(fid) or {} for r in records]
            obs(name, "i4", [c.get("code") if c.get("code") is not None else INT_FILL
                             for c in coded], INT_FILL, long_name=meta["name"],
                wod_taxa_variable_id=np.int32(fid))
            if any(c.get("originator_text") for c in coded):
                obs(f"{name}_originator_text", str, [c.get("originator_text") for c in coded],
                    None, long_name=f"{meta['name']}, as written")
        else:                                           # 20 Originator's unit, free text
            obs(name, str, [r["fields"].get(fid) for r in records], None,
                long_name=meta["name"], wod_taxa_variable_id=np.int32(fid))
    return written


# Thousands grouping only: '1,700' is 1700, but '0,5' is a decimal comma.
_THOUSANDS = re.compile(r"[-+]?[1-9]\d{0,2}(?:,\d{3})+(?:\.\d+)?")


def _float(x) -> float:
    if x in (None, ""):
        return np.nan
    s = str(x).strip()
    if _THOUSANDS.fullmatch(s):
        s = s.replace(",", "")
    try:
        f = float(s)
    except (TypeError, ValueError):
        return np.nan
    return f if np.isfinite(f) else np.nan
